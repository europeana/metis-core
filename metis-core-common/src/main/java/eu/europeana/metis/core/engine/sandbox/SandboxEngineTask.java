package eu.europeana.metis.core.engine.sandbox;

import eu.europeana.metis.core.engine.base.DataRevision;
import eu.europeana.metis.core.engine.base.EngineTask;
import eu.europeana.metis.core.engine.base.EngineTaskKey;
import eu.europeana.metis.core.engine.base.task.input.DepublishInputDataEndpoint;
import eu.europeana.metis.core.engine.base.task.input.HttpHarvestInputDataEndpoint;
import eu.europeana.metis.core.engine.base.task.input.InputDataEndpoint;
import eu.europeana.metis.core.engine.base.task.input.InternalInputDataEndpoint;
import eu.europeana.metis.core.engine.base.task.input.OaiHarvestInputDataEndpoint;
import eu.europeana.metis.sandbox.controller.task.input.InputMetadataRequest;
import eu.europeana.metis.sandbox.controller.task.input.InternalInputMetadataRequest;
import eu.europeana.metis.sandbox.controller.task.input.OaiHarvestInputMetadataRequest;
import eu.europeana.metis.sandbox.controller.task.input.SandboxTask;
import eu.europeana.metis.sandbox.controller.task.input.SandboxTaskKey;
import java.util.Arrays;
import java.util.Map;
import java.util.Map.Entry;
import java.util.Set;
import java.util.stream.Collectors;
import lombok.Getter;

@Getter
public class SandboxEngineTask extends EngineTask {

  SandboxTask sandboxTask = new SandboxTask();

  /**
   * Constructs an EngineTask with specified parameters, input data endpoint, and output data revision.
   *
   * @param parameters Map of EngineTaskKey and String values used to configure the task. Must not be null.
   * @param inputDataEndpoint InputDataEndpoint representing the input data source for the task. Must not be null.
   * @param outputDataRevision DataRevision representing the output data revision generated by the task. Must not be null.
   */
  protected SandboxEngineTask(Map<EngineTaskKey, String> parameters,
      InputDataEndpoint inputDataEndpoint,
      DataRevision outputDataRevision) {
    super(parameters, inputDataEndpoint, outputDataRevision);
    setParameters();
    setInputDataLocation();
    setOutputRevision();
  }

  private void setParameters() {
    Set<String> validKeys = Arrays.stream(SandboxTaskKey.values())
                                  .map(Enum::name)
                                  .collect(Collectors.toSet());

    Map<SandboxTaskKey, String> sandboxParameters =
        parameters.entrySet().stream()
                  .filter(entry -> validKeys.contains(entry.getKey().name()))
                  .collect(Collectors.toMap(
                      entry ->
                          SandboxTaskKey.valueOf(entry.getKey().name()),
                      Entry::getValue
                  ));
    sandboxTask.setParameters(sandboxParameters);
  }

  private void setInputDataLocation() {
    InputMetadataRequest inputMetadataRequest = switch (this.inputDataEndpoint) {
      case OaiHarvestInputDataEndpoint oaiHarvestInputDataParameters ->
          new OaiHarvestInputMetadataRequest(
          oaiHarvestInputDataParameters.url(), oaiHarvestInputDataParameters.set(),
          oaiHarvestInputDataParameters.metadataPrefix(),
          oaiHarvestInputDataParameters.from(), oaiHarvestInputDataParameters.until());
      case HttpHarvestInputDataEndpoint ignored ->
          throw new IllegalArgumentException("HttpHarvestInputDataEndpoint is not supported for sandbox tasks");
      case InternalInputDataEndpoint internalInputDataEndpoint ->
          new InternalInputMetadataRequest(internalInputDataEndpoint.sourceExecutionId());
      case DepublishInputDataEndpoint ignored ->
          throw new IllegalArgumentException("DepublishInputDataEndpoint is not supported for sandbox tasks");
    };
    sandboxTask.setInputMetadataRequest(inputMetadataRequest);
  }

  private void setOutputRevision() {

  }
}
